// Shared "smart" frame picker — TWO-STAGE approach:
// Stage 1: Extract many frames (4fps, up to 120), pre-filter black/tiny, downselect to 20.
// Stage 2: Send 20 candidates to Gemini → ranked top-3 best + face + outfit frames.
// Returns [{ label, base64, mimeType }]. User gets multiple good options, not just one guess.
async function smartPickFrames(videoPath, sessionDir) {
  const framesDir = path.join(sessionDir, 'frames');
  fs.mkdirSync(framesDir, { recursive: true });

  // ── STAGE 1: Extract & pre-filter ──────────────────────────────────────────
  // 4fps × 30s = ~120 frames. Quality 1 = max JPEG quality for sharp candidates.
  try {
    await execFileAsync(ffmpegPath, [
      '-i', videoPath,
      '-vf', 'fps=4',
      '-frames:v', '120',
      '-q:v', '1',
      path.join(framesDir, 'cand_%04d.jpg'),
    ], { timeout: 120_000 });
  } catch (ffErr) {
    log.warn('smart_frame_ffmpeg_failed', { error: ffErr.message });
    throw new AppError('Could not read that video — is it a supported format (mp4/mov/webm)?', 422, 'FFMPEG_FAILED');
  }

  let allFrames = fs.readdirSync(framesDir).filter((f) => f.endsWith('.jpg')).sort();
  if (!allFrames.length) throw new AppError('No frames could be sampled from the video', 422, 'NO_FRAMES');

  // Pre-filter: kill black/transition frames (they're tiny because JPEG compresses solid
  // colors to almost nothing). Any frame under 8KB is likely black or a solid-color transition.
  const MIN_FILE_SIZE = 8_000;
  allFrames = allFrames.filter((f) => {
    try { return fs.statSync(path.join(framesDir, f)).size >= MIN_FILE_SIZE; } catch { return true; }
  });
  if (!allFrames.length) {
    // All filtered out — re-read without filter
    allFrames = fs.readdirSync(framesDir).filter((f) => f.endsWith('.jpg')).sort();
  }

  // Downselect to 20 evenly spaced candidates for Gemini
  const MAX_CAND = 20;
  const step = Math.max(1, Math.floor(allFrames.length / MAX_CAND));
  const picked = [];
  for (let i = 0; i < allFrames.length && picked.length < MAX_CAND; i += step) picked.push(allFrames[i]);
  const images = picked.map((f) => ({ base64Data: fs.readFileSync(path.join(framesDir, f)).toString('base64'), mimeType: 'image/jpeg' }));

  log.info('smart_pick_stage1', { totalExtracted: allFrames.length, afterFilter: allFrames.length, candidates: images.length });

  // ── STAGE 2: Gemini vision ranking ─────────────────────────────────────────
  const prompt = `You are given ${images.length} still frames (numbered 1 to ${images.length}, in time order) sampled from a short social media video of ONE person.

Your job: RANK the frames and return the BEST options. Return ONLY minified JSON, no markdown fences, exactly this shape:
{"top3": [<number>, <number>, <number>], "faceFrame": <number>, "outfitFrames": [<number>, ...]}

RANKING RULES for top3 — rank the 3 BEST frames in order (index 0 = absolute best). Each frame in top3 MUST satisfy ALL of these:
  1. FACE CLEARLY VISIBLE — her face is turned toward the camera, eyes WIDE OPEN (not mid-blink, not squinting, not closed), mouth natural (not wide open mid-speech/yawn)
  2. FACE NOT COVERED — no hands, hair, phone, hat, clothing, props, or text covering any part of the face
  3. SHARP FOCUS — no motion blur on the face or body, crisp details, not blurry
  4. BODY VISIBLE — as much body visible as possible (head-to-toe preferred, at minimum head-to-waist). NOT just a head/shoulders crop, NOT shot from behind
  5. GOOD POSE — natural, flattering, not awkward mid-movement or mid-transition
  6. WELL LIT — face and body clearly illuminated, not in heavy shadow or overexposed
  7. FRONT-FACING — she is facing TOWARD the camera. Profile views, back views, and side angles are WORSE than front-facing or 3/4 angles

The 3 frames in top3 should be DIFFERENT moments (not adjacent/similar). Spread them across the video.

faceFrame = The single frame with the ABSOLUTE CLEAREST view of her face:
  - Eyes MUST be open and looking forward/at camera
  - Face fully unobstructed — nothing covering any facial feature
  - Sharpest focus on face (no motion blur)
  - Closest to front-facing as possible
  - Can be the same as top3[0] if that's also the best face

outfitFrames = One frame per DISTINCT complete outfit she is WEARING (not holding):
  - Show the full outfit clearly — prefer wider/full-body shots
  - Face also visible if possible
  - One entry per distinct outfit; if only one outfit, one number

HARD DISQUALIFICATION — a frame CANNOT be in top3 or faceFrame if ANY of these are true:
  ✗ Eyes closed, mid-blink, or squinting
  ✗ Face turned AWAY from camera (back of head, looking away, profile)
  ✗ Face covered/blocked by hands, hair, phone, props, text overlay, or graphics
  ✗ Heavy motion blur (person or camera shaking)
  ✗ Person mostly out of frame, cut off at neck, or only showing back/behind
  ✗ Black/dark frame, transition frame, or title card
  ✗ Face in heavy shadow or silhouette

If fewer than 3 frames pass all criteria, return only the ones that do.
Use 1-based frame numbers only. No other text.`;

  const apiKeyManager = require('../services/apiKeyManager');
  const geminiBackend = require('../services/geminiBackend');
  const apiKey = apiKeyManager.getActiveKey();
  const text = await geminiBackend.analyzeImagesWithPrompt(apiKey, images, prompt);

  let parsed = null;
  try {
    parsed = JSON.parse(String(text).trim().replace(/^```(?:json)?\s*/i, '').replace(/\s*```$/i, ''));
  } catch {
    const m = String(text).match(/\{[\s\S]*\}/);
    if (m) { try { parsed = JSON.parse(m[0]); } catch { /* ignore */ } }
  }

  const clamp = (n) => (Number.isInteger(n) && n >= 1 && n <= images.length ? n - 1 : -1);
  const out = [];
  const seen = new Set();

  // Top 3 ranked frames (best options for the user)
  const top3 = Array.isArray(parsed?.top3) ? parsed.top3 : [];
  let rank = 0;
  for (const t of top3) {
    const idx = clamp(t);
    if (idx < 0 || seen.has(idx)) continue;
    rank += 1;
    seen.add(idx);
    out.push({ label: rank === 1 ? 'best' : `pick${rank}`, base64: images[idx].base64Data, mimeType: 'image/jpeg' });
  }

  // Backwards compat: if Gemini returned old format with bestFrame instead of top3
  if (!top3.length) {
    const bestIdx = clamp(parsed?.bestFrame);
    if (bestIdx >= 0) { out.push({ label: 'best', base64: images[bestIdx].base64Data, mimeType: 'image/jpeg' }); seen.add(bestIdx); }
  }

  // faceFrame (if not already in top3)
  const faceIdx = clamp(parsed?.faceFrame);
  if (faceIdx >= 0 && !seen.has(faceIdx)) { out.push({ label: 'face', base64: images[faceIdx].base64Data, mimeType: 'image/jpeg' }); seen.add(faceIdx); }

  // outfitFrames
  const outfitList = Array.isArray(parsed?.outfitFrames) ? parsed.outfitFrames : [];
  let n = 0;
  for (const oi of outfitList) {
    const idx = clamp(oi);
    if (idx < 0 || seen.has(idx)) continue;
    seen.add(idx); n += 1;
    out.push({ label: outfitList.length > 1 ? `outfit${n}` : 'outfit', base64: images[idx].base64Data, mimeType: 'image/jpeg' });
  }

  // Fallback: model gave nothing usable → return the middle candidate
  if (!out.length) {
    const mid = Math.floor(images.length / 2);
    out.push({ label: 'frame', base64: images[mid].base64Data, mimeType: 'image/jpeg' });
  }
  log.info('smart_frames_done', { candidates: images.length, returned: out.length, top3: top3.slice(0, 3), faceIdx });
  return out;
}

