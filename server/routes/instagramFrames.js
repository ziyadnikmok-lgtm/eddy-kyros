// Body: { urls: [...] } — runs ONE Apify job for all Instagram links and returns each
// post's public CDN media URL. No cookies, no IP block (Apify scrapes on its side).
router.post('/resolve-media-batch', async (req, res, next) => {
  try {
    const { urls } = req.body;
    if (!Array.isArray(urls) || urls.length === 0) throw new AppError('"urls" array is required', 400, 'VALIDATION_ERROR');
    const apiKeyManager = require('../services/apiKeyManager');
    let token = '';
    try { token = apiKeyManager.getApifyKey(); } catch {}
    if (!token) throw new AppError('No Apify API key set. Add it in API Keys first.', 400, 'NO_APIFY_KEY');

    const clean = urls.filter((u) => typeof u === 'string' && u.startsWith('http')).slice(0, 500);
    const axios = require('axios');
    const resp = await axios.post(
      `https://api.apify.com/v2/acts/apify~instagram-scraper/run-sync-get-dataset-items?token=${encodeURIComponent(token)}`,
      { directUrls: clean, resultsLimit: clean.length, resultsType: 'posts', addParentData: false },
      { timeout: 300_000, headers: { 'Content-Type': 'application/json' } }
    );
    const items = Array.isArray(resp.data) ? resp.data : [];
    // Do NOT guess 'Image' when the type is missing — a partial Apify response for a reel can
    // arrive with only a displayUrl (its ▶ cover), and defaulting it to 'Image' would make the
    // client save that cover. Leave unknown types blank so the client fails safe + retries.
    const typeOf = (o) => o.type || (o.videoUrl ? 'Video' : '');
    const out = items.map((it) => ({
      url: it.url || it.inputUrl || '',
      type: typeOf(it),
      productType: it.productType || null,
      videoUrl: it.videoUrl || null,
      displayUrl: it.displayUrl || it.image || (Array.isArray(it.images) ? it.images[0] : null) || null,
      // Carousels (Sidecar) only carry a cover at the top level — expose each slide so the
      // client can pick a real one (a video slide → frame it; an image slide → use it) and
      // never save the carousel's ▶ cover.
      childPosts: Array.isArray(it.childPosts) ? it.childPosts.map((c) => ({
        type: typeOf(c),
        videoUrl: c.videoUrl || null,
        displayUrl: c.displayUrl || null,
      })) : [],
      error: it.error || it.errorDescription || null,
    }));
    log.info('apify_resolve_batch', { requested: clean.length, returned: out.length, withMedia: out.filter((o) => o.videoUrl || o.displayUrl).length });
    res.json({ success: true, data: { items: out } });
  } catch (err) {
    if (err.response) {
      log.warn('apify_resolve_batch_http', { status: err.response.status });
      return next(new AppError(`Apify error ${err.response.status}. Check your Apify key/credits.`, 502, 'APIFY_ERROR'));
    }
    next(err);
  }
});

