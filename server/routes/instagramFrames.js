function detectPlatform(url) {
  if (url && INSTAGRAM_URL_RE.test(url)) return 'instagram';
  if (url && TIKTOK_URL_RE.test(url)) return 'tiktok';
  if (url && X_URL_RE.test(url)) return 'x';
  return null;
}

