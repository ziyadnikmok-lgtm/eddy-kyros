const SCRAPER_PROXY_PATH = path.join(os.homedir(), '.kyros-scraper-proxy.txt');

// Optional proxy for the scraper (keeps your real IP out of the scraping path).
// Set via env KYROS_SCRAPER_PROXY or the save-proxy endpoint (file).
function resolveScraperProxy() {
  const env = process.env.KYROS_SCRAPER_PROXY || process.env.SCRAPER_PROXY;
  if (env && env.trim()) return env.trim();
  try {
    if (fs.existsSync(SCRAPER_PROXY_PATH)) {
      const v = fs.readFileSync(SCRAPER_PROXY_PATH, 'utf8').trim();
      if (v) return v;
    }
  } catch {}
  return '';
}

// Convert a browser-extension JSON cookie export (Cookie-Editor etc.) to Netscape.
function jsonCookiesToNetscape(jsonStr) {
  let arr;
  try { arr = JSON.parse(jsonStr); } catch { return null; }
  if (!Array.isArray(arr) || arr.length === 0) return null;
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Kyros Studio', ''];
  for (const c of arr) {
    if (!c || !c.name || typeof c.value === 'undefined') continue;
    const domain = c.domain || '.instagram.com';
    const includeSub = domain.startsWith('.') ? 'TRUE' : 'FALSE';
    const domField = c.httpOnly ? `#HttpOnly_${domain}` : domain;
    const cpath = c.path || '/';
    const secure = c.secure ? 'TRUE' : 'FALSE';
    const exp = c.session ? 0 : (Math.floor(Number(c.expirationDate || c.expires || 0)) || 0);
    lines.push([domField, includeSub, cpath, secure, String(exp), c.name, c.value].join('\t'));
  }
  return lines.length > 3 ? lines.join('\n') + '\n' : null;
}

// Best-effort yt-dlp + gallery-dl self-update on server start (IG/TikTok change their
// internals often and break these tools; keeping them current avoids silent failures).
// Throttled to once per 24h so it doesn't slow every restart.
const YTDLP_UPDATE_STAMP = path.join(os.homedir(), '.kyros-ytdlp-updated.txt');
let _ytDlpUpdated = false;

function _shouldUpdateYtDlp() {
  try {
    if (fs.existsSync(YTDLP_UPDATE_STAMP)) {
      const last = Number(fs.readFileSync(YTDLP_UPDATE_STAMP, 'utf8').trim()) || 0;
      if (Date.now() - last < 24 * 60 * 60 * 1000) return false;
    }
  } catch {}
  return true;
}

function runYtDlpSelfUpdate() {
  if (_ytDlpUpdated) return;
  _ytDlpUpdated = true;
  if (!_shouldUpdateYtDlp()) return;
  try { fs.writeFileSync(YTDLP_UPDATE_STAMP, String(Date.now()), 'utf8'); } catch {}

  const ytDlp = findYtDlp();
  // pip-installed yt-dlp can't self-update via -U; update via the matching Python's pip.
  const pipUpdate = () => {
    let python = 'python';
    const m = ytDlp.match(/^(.*)[\\/]Scripts[\\/]yt-dlp\.exe$/i);
    if (m) python = path.join(m[1], 'python.exe');
    execFile(python, ['-m', 'pip', 'install', '--upgrade', 'yt-dlp', 'gallery-dl'], { timeout: 180_000 }, (err, stdout) => {
      if (err) log.warn('yt_dlp_pip_update_failed', { error: (err.stderr || err.message || '').slice(0, 200) });
      else log.info('yt_dlp_pip_update_ok', { out: String(stdout || '').trim().slice(-160) });
    });
  };

  try {
    execFile(ytDlp, ['-U'], { timeout: 90_000 }, (err, stdout) => {
      if (err) {
        const msg = err.stderr || err.message || '';
        if (/pip|wheel|pypi/i.test(msg)) { pipUpdate(); return; }
        log.warn('yt_dlp_selfupdate_failed', { error: msg.slice(0, 200) });
      } else {
        log.info('yt_dlp_selfupdate_ok', { out: String(stdout || '').trim().slice(0, 160) });
      }
    });
  } catch (e) {
    log.warn('yt_dlp_selfupdate_error', { error: e.message });
  }
}

// Apify fallback (Instagram only): when the local tools can't download a post (bad/expired
// cookies, private, blocked IP), fetch its image(s) via Apify — which uses its own token,
// so it can rescue what cookies can't. Writes images into sessionDir; returns true if any saved.
async function tryApifyImageFallback(url, sessionDir) {
  const apiKeyManager = require('../services/apiKeyManager');
  let apifyToken = '';
  try { apifyToken = apiKeyManager.getApifyKey(); } catch {}
  if (!apifyToken) return false;
  const { runPostActor, normalizePostsFromItems } = require('../services/postClone/apifyFetcher');
  const axios = require('axios');
  const items = await runPostActor({ url, limit: 1, apifyToken });
  const raw = Array.isArray(items) ? items[0] : null;
  // NEVER save a video's cover thumbnail — Instagram bakes a ▶ play button into reel/clip
  // covers. If this post is a video (reel/clip) and has no genuine image slides, bail so it
  // fails cleanly instead of importing a ▶ frame.
  const rawType = String(raw?.type || raw?.productType || '').toLowerCase();
  const isVideoPost = !!raw?.videoUrl || /video|clip/.test(rawType);
  const childImageUrls = Array.isArray(raw?.childPosts)
    ? raw.childPosts.filter(c => !c.videoUrl && c.displayUrl).map(c => c.displayUrl)
    : [];
  if (isVideoPost && childImageUrls.length === 0) {
    log.info('media_frames_apify_fallback_skipped_video', { url });
    return false;
  }
  let imageUrls;
  if (rawType.includes('sidecar') && childImageUrls.length) {
    imageUrls = childImageUrls; // carousel: only the genuine (non-video) image slides
  } else {
    const posts = normalizePostsFromItems(items || []);
    const post = Array.isArray(posts) ? posts[0] : null;
    imageUrls = post && Array.isArray(post.imageUrls) ? post.imageUrls.filter(Boolean) : [];
  }
  if (imageUrls.length === 0) return false;
  let saved = 0;
  for (let i = 0; i < imageUrls.length && i < 12; i += 1) {
    try {
      const resp = await axios.get(imageUrls[i], { responseType: 'arraybuffer', timeout: 30_000 });
      const ct = String(resp.headers['content-type'] || '');
      const ext = ct.includes('png') ? '.png' : ct.includes('webp') ? '.webp' : '.jpg';
      fs.writeFileSync(path.join(sessionDir, `apify_${String(i).padStart(3, '0')}${ext}`), Buffer.from(resp.data));
      saved += 1;
    } catch { /* skip this image */ }
  }
  return saved > 0;
}

// GET /api/instagram-frames/cookies-status
// Returns whether cookies.txt are saved and their basic info
router.get('/cookies-status', (req, res) => {
  const igExists = fs.existsSync(IG_COOKIES_PATH);
  const ttExists = fs.existsSync(TT_COOKIES_PATH);
  const xExists = fs.existsSync(X_COOKIES_PATH);
  
  let igInfo = { hasCookies: false };
  let ttInfo = { hasCookies: false };
  let xInfo = { hasCookies: false };

  if (igExists) {
    try {
      const stat = fs.statSync(IG_COOKIES_PATH);
      const content = fs.readFileSync(IG_COOKIES_PATH, 'utf8');
      const hasInstagram = content.includes('instagram.com');
      igInfo = {
        hasCookies: true,
        hasInstagram,
        savedAt: stat.mtimeMs,
        sizeBytes: stat.size,
      };
    } catch {}
  }

  if (ttExists) {
    try {
      const stat = fs.statSync(TT_COOKIES_PATH);
      const content = fs.readFileSync(TT_COOKIES_PATH, 'utf8');
      const hasTikTok = content.includes('tiktok.com');
      ttInfo = {
        hasCookies: true,
        hasTikTok,
        savedAt: stat.mtimeMs,
        sizeBytes: stat.size,
      };
    } catch {}
  }

  if (xExists) {
    try {
      const stat = fs.statSync(X_COOKIES_PATH);
      const content = fs.readFileSync(X_COOKIES_PATH, 'utf8');
      const hasX = content.includes('x.com') || content.includes('twitter.com');
      xInfo = {
        hasCookies: true,
        hasX,
        savedAt: stat.mtimeMs,
        sizeBytes: stat.size,
      };
    } catch {}
  }

  res.json({
    success: true,
    data: {
      instagram: igInfo,
      tiktok: ttInfo,
      x: xInfo,
      // Backward compatibility fields for frontend:
      hasCookies: igExists,
      hasInstagram: igExists && igInfo.hasInstagram,
      savedAt: igExists ? igInfo.savedAt : null,
      sizeBytes: igExists ? igInfo.sizeBytes : null,
    },
  });
});

// POST /api/instagram-frames/save-cookies
// Body: { cookies: "<netscape cookies.txt content>", platform?: "instagram" | "tiktok" | "x" }
router.post('/save-cookies', (req, res, next) => {
  try {
    const { cookies, platform } = req.body;
    if (!cookies || typeof cookies !== 'string' || cookies.trim().length < 20) {
      throw new AppError('Invalid cookies content', 400, 'VALIDATION_ERROR');
    }
    let trimmed = cookies.trim();
    // Accept browser-extension JSON cookie exports too (Cookie-Editor etc.) — convert them.
    if (trimmed.startsWith('[')) {
      const converted = jsonCookiesToNetscape(trimmed);
      if (!converted) {
        throw new AppError('Could not parse the JSON cookies. Paste a valid cookie export.', 400, 'VALIDATION_ERROR');
      }
      trimmed = converted;
    } else if (!trimmed.startsWith('# Netscape HTTP Cookie File') && !trimmed.includes('\tTRUE\t') && !trimmed.includes('\tFALSE\t')) {
      throw new AppError('This doesn\'t look like a Netscape cookies.txt or JSON cookie export. Use the "Get cookies.txt LOCALLY" or "Cookie-Editor" browser extension.', 400, 'VALIDATION_ERROR');
    }

    let targetPath = IG_COOKIES_PATH;
    let selectedPlatform = 'instagram';

    if (platform === 'tiktok' || (platform !== 'instagram' && platform !== 'x' && trimmed.includes('tiktok.com'))) {
      targetPath = TT_COOKIES_PATH;
      selectedPlatform = 'tiktok';
    } else if (platform === 'x' || (platform !== 'instagram' && platform !== 'tiktok' && (trimmed.includes('x.com') || trimmed.includes('twitter.com')))) {
      targetPath = X_COOKIES_PATH;
      selectedPlatform = 'x';
    }

    fs.writeFileSync(targetPath, trimmed, 'utf8');
    log.info('cookies_saved', { platform: selectedPlatform, size: trimmed.length });
    res.json({ success: true, data: { saved: true, platform: selectedPlatform } });
  } catch (err) {
    next(err);
  }
});

